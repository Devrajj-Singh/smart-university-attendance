/**
 * Seed past realistic sessions and attendance for realistic university reports.
 */
export function seedRealisticHistory(db: any) {
  try {
    // 1. Update/Upsert clean names for all 65 students
    for (const student of STUDENT_ROSTER) {
      const email = student.name.toLowerCase().replace(/\s+/g, '.') + '@university.edu';
      const cardId = 'CARD-' + student.id;
      const biometricId = 'IRIS-' + student.id;

      const existing = db.prepare('SELECT user_id FROM students WHERE user_id = ?').get(student.id);
      if (existing) {
        db.prepare('UPDATE students SET name = ?, email = ? WHERE user_id = ?').run(student.name, email, student.id);
      } else {
        db.prepare(`
          INSERT INTO students (user_id, name, email, card_id, biometric_id, class_id)
          VALUES (?, ?, ?, ?, ?, ?)
        `).run(student.id, student.name, email, cardId, biometricId, student.classId);
      }
    }

    // 2. Check if past sessions already exist
    const pastCount = db.prepare("SELECT COUNT(*) as count FROM attendance_sessions WHERE session_id LIKE 'PAST-SES-%'").get() as any;
    if (pastCount && pastCount.count >= 16) {
      return; // Already seeded
    }

    // 3. Create 16 past sessions across the last month
    const pastSessions = [
      { id: 'PAST-SES-001', subject: 'SUB001', classId: 'CLS001', faculty: 'FAC001', date: '2026-09-15 09:00:00' },
      { id: 'PAST-SES-002', subject: 'SUB002', classId: 'CLS001', faculty: 'FAC002', date: '2026-09-17 10:15:00' },
      { id: 'PAST-SES-003', subject: 'SUB001', classId: 'CLS001', faculty: 'FAC001', date: '2026-09-22 09:00:00' },
      { id: 'PAST-SES-004', subject: 'SUB002', classId: 'CLS001', faculty: 'FAC002', date: '2026-09-24 10:15:00' },
      { id: 'PAST-SES-005', subject: 'SUB001', classId: 'CLS001', faculty: 'FAC001', date: '2026-09-29 09:00:00' },
      { id: 'PAST-SES-006', subject: 'SUB002', classId: 'CLS001', faculty: 'FAC002', date: '2026-10-01 10:15:00' },
      { id: 'PAST-SES-007', subject: 'SUB001', classId: 'CLS001', faculty: 'FAC001', date: '2026-10-06 09:00:00' },
      { id: 'PAST-SES-008', subject: 'SUB002', classId: 'CLS001', faculty: 'FAC002', date: '2026-10-08 10:15:00' },
      { id: 'PAST-SES-009', subject: 'SUB001', classId: 'CLS001', faculty: 'FAC001', date: '2026-10-13 09:00:00' },
      { id: 'PAST-SES-010', subject: 'SUB002', classId: 'CLS001', faculty: 'FAC002', date: '2026-10-15 10:15:00' },

      // Section B sessions
      { id: 'PAST-SES-011', subject: 'SUB001', classId: 'CLS002', faculty: 'FAC003', date: '2026-09-16 09:00:00' },
      { id: 'PAST-SES-012', subject: 'SUB002', classId: 'CLS002', faculty: 'FAC002', date: '2026-09-18 10:15:00' },
      { id: 'PAST-SES-013', subject: 'SUB001', classId: 'CLS002', faculty: 'FAC003', date: '2026-09-23 09:00:00' },
      { id: 'PAST-SES-014', subject: 'SUB002', classId: 'CLS002', faculty: 'FAC002', date: '2026-09-25 10:15:00' },
      { id: 'PAST-SES-015', subject: 'SUB001', classId: 'CLS002', faculty: 'FAC003', date: '2026-09-30 09:00:00' },
      { id: 'PAST-SES-016', subject: 'SUB002', classId: 'CLS002', faculty: 'FAC002', date: '2026-10-07 10:15:00' },
    ];

    for (const s of pastSessions) {
      db.prepare(`
        INSERT OR IGNORE INTO attendance_sessions 
        (session_id, subject_id, class_id, classroom_id, scheduled_faculty_id, actual_faculty_id, start_time, end_time, status, session_type)
        VALUES (?, ?, ?, 'ROOM001', ?, ?, ?, ?, 'CLOSED', 'AUTOMATIC')
      `).run(s.id, s.subject, s.classId, s.faculty, s.faculty, s.date, s.date);
    }

    // 4. Generate realistic attendance distributions:
    // Some students are high attendance (85%-100%), some borderline (70%-74%), some defaulters (<65%)
    const students = db.prepare('SELECT user_id, class_id FROM students').all() as any[];

    for (const student of students) {
      const studentNum = parseInt(student.user_id.slice(-2), 10);
      const studentSessions = pastSessions.filter(s => s.classId === student.classId);

      // Define target attendance rate based on student index
      let targetRate = 0.88; // Default 88%
      if (studentNum % 9 === 0) {
        targetRate = 0.55; // Critical defaulter (55%)
      } else if (studentNum % 5 === 0) {
        targetRate = 0.70; // Warning zone (70%)
      } else if (studentNum % 3 === 0) {
        targetRate = 0.94; // Star student (94%)
      }

      for (let idx = 0; idx < studentSessions.length; idx++) {
        const sess = studentSessions[idx];
        const hash = (studentNum * 17 + idx * 23) % 100;
        const attended = hash < (targetRate * 100);

        if (attended) {
          const isLate = hash % 7 === 0;
          const status = isLate ? 'LATE' : 'PRESENT';
          const method = idx % 2 === 0 ? 'CAMERA_CARD' : 'CAMERA_IRIS';
          const recordId = 'REC-' + sess.id + '-' + student.user_id;

          db.prepare(`
            INSERT OR IGNORE INTO attendance_records 
            (record_id, session_id, student_id, timestamp, method, status, synced, device_id)
            VALUES (?, ?, ?, ?, ?, ?, 1, 'MOBILE_EDGE_SCANNER')
          `).run(recordId, sess.id, student.user_id, sess.date, method, status);
        }
      }
    }

    console.log('[DB] Realistic university semester attendance records successfully seeded.');
  } catch (err) {
    console.error('[DB] Error seeding realistic history:', err);
  }
}
